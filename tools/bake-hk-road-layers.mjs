#!/usr/bin/env node
/**
 * bake-hk-road-layers — P1 enrichment: OSM bridge/layer/oneway → sidecar + GEO stamp.
 *
 * Reads tools/data-hk/osm_roads.json (already cached), writes:
 *   data/hk-road-layers.json
 *   js/hk-road-layers-data.js
 *
 * Also patches tools/build-hk-geodata.mjs consumers: optional --stamp-geo rewrites
 * roadLines layer/bridge into GEO.roads trailing fields via a rebuild note.
 * This script alone emits the sidecar; build-hk-geodata.mjs reads layer tags live.
 *
 * Usage: node tools/bake-hk-road-layers.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = process.env.GEO_DATA || join(ROOT, 'tools/data-hk');

const PEDDER_LAT = 22.28155;
const PEDDER_LON = 114.15785;
const A = 6378137.0;
const E2 = 6.69437999014e-3;
const PHI0 = (PEDDER_LAT * Math.PI) / 180;
const SIN0 = Math.sin(PHI0);
const NRAD = A / Math.sqrt(1 - E2 * SIN0 * SIN0);
const MRAD = (A * (1 - E2)) / Math.pow(1 - E2 * SIN0 * SIN0, 1.5);
const KX = (Math.PI / 180) * NRAD * Math.cos(PHI0);
const KY = (Math.PI / 180) * MRAD;
const toWorld = (lon, lat) => {
  const e = (lon - PEDDER_LON) * KX;
  const n = (lat - PEDDER_LAT) * KY;
  return [e, -n];
};

function parseLayer(t) {
  const raw = t.layer;
  if (raw == null || raw === '') return 0;
  const n = Number.parseInt(String(raw), 10);
  return Number.isFinite(n) ? n : 0;
}

function parseOneway(t) {
  if (t.oneway === 'yes') return 1;
  if (t.oneway === '-1') return -1;
  return 0;
}

function isBridge(t) {
  const b = t.bridge;
  return b === 'yes' || b === 'viaduct' || b === 'movable' || b === 'cantilever' || b === 'covered';
}

function isTunnel(t) {
  return t.tunnel === 'yes' || t.tunnel === 'building_passage' || t.tunnel === 'culvert';
}

const osm = JSON.parse(readFileSync(join(DATA, 'osm_roads.json'), 'utf8'));
const rows = [];
let withLayer = 0;
let withBridge = 0;
let withOneway = 0;
let withLanes = 0;

for (const e of osm.elements || []) {
  if (e.type !== 'way' || !e.geometry || e.geometry.length < 2) continue;
  const t = e.tags || {};
  if (!t.highway) continue;
  const layer = parseLayer(t);
  const bridge = isBridge(t) ? 1 : 0;
  const tunnel = isTunnel(t) ? 1 : 0;
  const o = parseOneway(t);
  const lanes = Number.parseInt(t.lanes || '0', 10) || 0;
  if (layer) withLayer++;
  if (bridge) withBridge++;
  if (o) withOneway++;
  if (lanes) withLanes++;
  // Skip at-grade two-way with no lanes tag to keep sidecar small? Keep all with any elev signal or lanes.
  if (!layer && !bridge && !tunnel && !o && !lanes) continue;
  const mid = e.geometry[Math.floor(e.geometry.length / 2)];
  const [x, z] = toWorld(mid.lon, mid.lat);
  const name = (t.name || t.ref || t.highway || '').toUpperCase();
  rows.push({
    id: e.id,
    name,
    x: Math.round(x * 10) / 10,
    z: Math.round(z * 10) / 10,
    lanes: lanes || undefined,
    o: o || undefined,
    b: bridge || undefined,
    l: layer || undefined,
    t: tunnel || undefined,
  });
}

const pack = {
  source: 'osm',
  attribution: '© OpenStreetMap contributors (ODbL)',
  generated: new Date().toISOString(),
  stats: {
    ways: rows.length,
    withLayer,
    withBridge,
    withOneway,
    withLanes,
  },
  roads: rows,
};

mkdirSync(join(ROOT, 'data'), { recursive: true });
writeFileSync(join(ROOT, 'data/hk-road-layers.json'), JSON.stringify(pack));
writeFileSync(
  join(ROOT, 'js/hk-road-layers-data.js'),
  `// GENERATED by tools/bake-hk-road-layers.mjs — do not edit by hand.
export const HK_ROAD_LAYERS_META = ${JSON.stringify({ source: pack.source, attribution: pack.attribution, generated: pack.generated, stats: pack.stats }, null, 2)};
export const HK_ROAD_LAYERS = ${JSON.stringify(rows)};
`,
);
console.log('[bake-hk-road-layers]', pack.stats);
